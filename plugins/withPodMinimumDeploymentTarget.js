// Xcode 27 refuses to build any target whose IPHONEOS_DEPLOYMENT_TARGET is
// below iOS 15, and several pods still ship *resource bundles* declaring
// 9.0-13.4 (SDWebImage, Sentry, RNSVG's filters, ReachabilitySwift,
// AsyncStorage's resources). Expo's post_install hook only raises the pod
// targets themselves, so a clean `pod install` still produces a project that
// won't compile. Raise everything CocoaPods generates to the app's own
// minimum.
//
// This has to happen in the Podfile rather than on the xcodebuild command
// line: a global IPHONEOS_DEPLOYMENT_TARGET would also drag down the
// AttendWidget target, whose Live Activity code needs ActivityViewContext
// (iOS 16.1+). Scoping it to the generated Pods projects leaves the app and
// extension targets at whatever they declare.
//
// The Podfile is regenerated by `expo prebuild` and ios/ is gitignored, so
// this lives as a config plugin instead of an edit to ios/Podfile.
const fs = require('fs');
const path = require('path');
const { withDangerousMod } = require('expo/config-plugins');

const MARKER = '# withPodMinimumDeploymentTarget';

// `platform :ios, <expr>` — capture the expression so the hook below tracks
// whatever the template (or ios.deploymentTarget) says, rather than pinning a
// version here that would silently drift.
const PLATFORM_LINE = /^platform :ios, (.+)$/m;

const POST_INSTALL_LINE = /^([ \t]*)post_install do \|installer\|$/m;

const HOOK = (indent) =>
  [
    `${indent}  ${MARKER}: resource bundles don't inherit the platform version,`,
    `${indent}  # and Xcode rejects anything below iOS 15.`,
    `${indent}  installer.generated_projects.each do |project|`,
    `${indent}    project.targets.each do |target|`,
    `${indent}      target.build_configurations.each do |config|`,
    `${indent}        existing = config.build_settings['IPHONEOS_DEPLOYMENT_TARGET']`,
    `${indent}        if existing.nil? || Gem::Version.new(existing.to_s) < Gem::Version.new(minimum_ios_version)`,
    `${indent}          config.build_settings['IPHONEOS_DEPLOYMENT_TARGET'] = minimum_ios_version`,
    `${indent}        end`,
    `${indent}      end`,
    `${indent}    end`,
    `${indent}  end`,
    '',
  ].join('\n');

function patchPodfile(contents) {
  if (contents.includes(MARKER)) return contents;

  const platformMatch = contents.match(PLATFORM_LINE);
  if (!platformMatch) {
    throw new Error(
      "withPodMinimumDeploymentTarget: couldn't find a `platform :ios, ...` line in the Podfile."
    );
  }
  const postInstallMatch = contents.match(POST_INSTALL_LINE);
  if (!postInstallMatch) {
    throw new Error(
      "withPodMinimumDeploymentTarget: couldn't find a `post_install do |installer|` block in the Podfile."
    );
  }

  return contents
    .replace(
      PLATFORM_LINE,
      () => `minimum_ios_version = ${platformMatch[1]}\nplatform :ios, minimum_ios_version`
    )
    .replace(POST_INSTALL_LINE, (line, indent) => `${line}\n${HOOK(indent)}`);
}

module.exports = function withPodMinimumDeploymentTarget(config) {
  return withDangerousMod(config, [
    'ios',
    (config) => {
      const podfile = path.join(config.modRequest.platformProjectRoot, 'Podfile');
      fs.writeFileSync(podfile, patchPodfile(fs.readFileSync(podfile, 'utf8')));
      return config;
    },
  ]);
};
